#!/usr/bin/env python3
"""gen_lab_docs.py — render docs/labs/*.md and docs/labs/README.md from LabSpec.

The JSON files under data/labs/ are the single source of truth for lab
exercises (ADR 0146); the markdown under docs/labs/ is build output. Never
hand-edit the generated files — edit the LabSpec and re-run:

    python3 scripts/gen_lab_docs.py            # regenerate in place
    python3 scripts/gen_lab_docs.py --check    # exit 1 if committed docs differ

Output is deterministic: labs render in file-name order, step tables render in
document order, no timestamps or locale-dependent formatting.
"""
import argparse
import difflib
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
LABS_DIR = REPO_ROOT / "data" / "labs"
DOCS_DIR = REPO_ROOT / "docs" / "labs"

GENERATED_NOTICE = (
    "<!-- AUTO-GENERATED by scripts/gen_lab_docs.py from data/labs/ — do not hand-edit. -->\n"
)

# Hand-authored docs that live under docs/labs/ alongside generated output.
# They are never overwritten and never reported as stale by --check.
HAND_WRITTEN = {"docs/labs/LABSPEC.md"}

# Shipped sample-data reference (fixed template content, not per-lab data):
# describes the gitignored data/samples/ rasters the labs reference by path.
