"""D8 capability enrichment applier (ADR 0146).

Injects the authored-only enrichment (summary / failure_modes / applicability /
teaching_use / extra prerequisites) into the v2 capability sidecars under
data/processing/algorithm_meta/capability/. Everything mechanically derivable
belongs to capability_knowledge_tool gen-meta — never hand-write it here.

Usage:
  python3 scripts/capability_enrichment.py [--check] [--strict]

  --check   verify every sidecar already carries the authored content (no write)
  --strict  require every rs: sidecar to be enriched (binary 111/111 gate)

Failure-mode codes are closed vocabulary (capability_catalog.cpp); `when` and
`remedy` are agent-facing Chinese text.
"""

