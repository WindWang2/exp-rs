def sync_relations() -> int:
    """把 authored 的 chains/exclusive 写入 capability_relations.json，
    保留 gen-meta 维护的 requires_shared_grid / grid_fixer。幂等。"""
    path = CAP_DIR / "capability_relations.json"
    if path.exists():
        doc = json.loads(path.read_text(encoding="utf-8"))
    else:
        doc = {}
    doc["schema_version"] = 1
    doc["chains"] = CHAINS
    doc["exclusive"] = EXCLUSIVE
    doc.setdefault("requires_shared_grid", [])
    doc.setdefault("grid_fixer", "rs:align")
    path.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"relations: {len(CHAINS)} chains, {len(EXCLUSIVE)} exclusive pairs")
    return 0

