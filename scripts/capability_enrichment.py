ENRICHMENT = {}
for family_dict in (OPTICAL, SPECTRAL, SAR, TERRAIN, TEMPORAL, CLASSIFICATION, CHANGE, OBIA, HYPER, RASTER_SPATIAL, IO):
    for op_id, content in family_dict.items():
        if op_id in ENRICHMENT:
            raise SystemExit(f"duplicate enrichment entry: {op_id}")
        ENRICHMENT[op_id] = content

def sidecar_paths():
    return sorted(CAP_DIR.glob("rs-*.json"))

def id_from_path(path: Path) -> str:
    return "rs:" + path.stem[len("rs-"):].replace("-", "_")

def apply(check: bool) -> int:
    problems = []
    enriched = 0
    for path in sidecar_paths():
        op_id = id_from_path(path)
        entry = ENRICHMENT.get(op_id)
        doc = json.loads(path.read_text(encoding="utf-8"))
        if entry is None:
            problems.append(f"{op_id}: no authored enrichment (coverage must be 111/111)")
            continue
        for failure in entry["failure_modes"]:
            if failure["code"] not in CLOSED_CODES:
                problems.append(f"{op_id}: failure code '{failure['code']}' not in closed vocabulary")
        cap = doc.setdefault("capability", {})
        cap["summary"] = entry["summary"]
        cap["applicability"] = entry["applicability"]
        cap["teaching_use"] = entry["teaching_use"]
        cap["failure_modes"] = entry["failure_modes"]
        merged = list(cap.get("prerequisites", []))
        for extra in entry["prerequisites_extra"]:
            if extra not in merged:
                merged.append(extra)
        cap["prerequisites"] = merged
        enriched += 1
        if not check:
            path.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    missing = [p.name for p in sidecar_paths() if id_from_path(p) not in ENRICHMENT]
    if missing:
        problems.append(f"missing enrichment for {len(missing)} operators: {', '.join(missing)}")
    for problem in problems:
        print("problem:", problem, file=sys.stderr)
    mode = "checked" if check else "applied"
    print(f"{mode}: {enriched}/{len(ENRICHMENT)} authored entries; {len(sidecar_paths())} sidecars on disk")
    return 0 if not problems else 1


